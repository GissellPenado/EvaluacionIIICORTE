--Creacion de la base de datos
CREATE DATABASE bd_laboratorio_orm

--Creación del esquema de la base de datos
CREATE SCHEMA  catalogos;

--Creación de la tabla de tipos de equipo
CREATE TABLE catalogos.tipo_equipo (
    id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(250),

    CONSTRAINT uq_tipo_equipo_nombre UNIQUE (nombre),
    CONSTRAINT ck_tipo_equipo_nombre
        CHECK (LENGTH(TRIM(nombre)) > 0)
);
--Creación de la tabla de equipos
CREATE TABLE catalogos.equipo (
	id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    estado VARCHAR(30) NOT NULL,
    cantidad INTEGER NOT NULL,
    id_tipo BIGINT NOT NULL,
	 CONSTRAINT uq_equipo_codigo UNIQUE (codigo),
	
	    CONSTRAINT ck_equipo_codigo
	        CHECK (LENGTH(TRIM(codigo)) > 0),
	
	    CONSTRAINT ck_equipo_nombre
	        CHECK (LENGTH(TRIM(nombre)) > 0),
	
	    CONSTRAINT ck_equipo_cantidad
	        CHECK (cantidad >= 0),
	
	    CONSTRAINT ck_equipo_estado
	        CHECK (
	            estado IN (
	                'Disponible',
	                'En mantenimiento',
	                'Fuera de servicio'
	            )
	        ),
		CONSTRAINT fk_equipo_tipo
        FOREIGN KEY (id_tipo)
        REFERENCES catalogos.tipo_equipo (id_tipo)
)


